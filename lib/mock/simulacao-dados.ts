// [pilotoId, kartId, melhorVoltaMs, gapMs, pontos]
type LinhaResultado = [string, string, number, number, number];

function montar(
  prefixoId: string,
  bateriaId: string,
  linhas: LinhaResultado[],
  voltaAtual?: number,
): Resultado[] {
  return linhas.map(([pilotoId, kartId, melhorVoltaMs, gapMs, pontos], i) => ({
    id: `${prefixoId}-${String(i + 1).padStart(2, "0")}`,
    bateriaId,
    pilotoId,
    kartId,
    posicao: i + 1,
    melhorVoltaMs,
    gapMs,
    pontos,
    ...(voltaAtual ? { voltaAtual } : {}),
  }));
}

